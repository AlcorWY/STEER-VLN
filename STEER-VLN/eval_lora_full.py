import os
import sys
import subprocess
from pathlib import Path
from datetime import datetime


ROOT = Path(__file__).resolve().parents[1]


def now():
    return datetime.now().strftime("%Y-%m-%d_%H-%M-%S")


def main():
    os.chdir(ROOT)

    final_dir = Path(os.environ.get(
        "STEER_VLN_FINAL_MODEL_DIR",
        "runs/STEER-VLN/train/final_model",
    ))

    log_dir = ROOT / "runs" / "code" / "STEER-VLN" / "logs" / "eval"
    log_dir.mkdir(parents=True, exist_ok=True)

    log_path = log_dir / f"eval_steer_vln_final_E3_integrated_{now()}.log"

    lora_path = final_dir / "lora_adapter_best"
    trend_path = final_dir / "m3c_trend_head_best.pt"
    kfm_path = final_dir / "keyframe_scorer_best.pt"
    vocab_path = final_dir / "simple_tokenizer_vocab.json"

    required_files = [
        trend_path,
        kfm_path,
        vocab_path,
        final_dir / "integrated_full_best.pt",
    ]
    required_dirs = [
        lora_path,
    ]

    for p in required_files:
        if not p.exists():
            raise FileNotFoundError(f"Missing required final_model file: {p}")

    for p in required_dirs:
        if not p.exists():
            raise FileNotFoundError(f"Missing required final_model dir: {p}")

    env = os.environ.copy()

    env.update({
        "OPENFLY_LOCAL_MODEL_PATH": "models/openfly-agent-7b",
        "HF_FALLBACK_REMOTE": "0",
        "HF_HUB_OFFLINE": "1",
        "TRANSFORMERS_OFFLINE": "1",
        "PYTHONUNBUFFERED": "1",
        "AIRSIM_PORT": "41451",
        "CUDA_VISIBLE_DEVICES": env.get("CUDA_VISIBLE_DEVICES", "0"),

        # Keep original AirSim startup/connect behavior.
        # No AirSim timeout retry is added here.
        "AIRSIM_STARTUP_WAIT": env.get("AIRSIM_STARTUP_WAIT", "60"),
        "AIRSIM_CONNECT_MAX_WAIT": env.get("AIRSIM_CONNECT_MAX_WAIT", "600"),
        "AIRSIM_CONNECT_RETRY_INTERVAL": env.get("AIRSIM_CONNECT_RETRY_INTERVAL", "5"),

        # Current STEER-VLN final E3 settings.
        "LORA_ADAPTER_PATH": str(lora_path),
        "M3C_TREND_HEAD_CHECKPOINT": str(trend_path),
        "LEARNED_KEYFRAME_CHECKPOINT": str(kfm_path),
        "LEARNED_KEYFRAME_VOCAB": str(vocab_path),

        "KEYFRAME_MODE": "learned_topk",
        "LEARNED_KEYFRAME_EXCLUDE_PREVIOUS": "1",
        "LEARNED_KEYFRAME_MAX_HISTORY": "8",
        "LEARNED_KEYFRAME_TOPK": "3",

        # Final action is still generated by OpenFly/LoRA.
        # Trend state is prompt conditioning only.
        "TREND_CONDITIONED": "1",
        "TREND_STATE_TEMPORAL_WINDOW": "3",
        "TREND_STATE_STOP_THRESHOLD": "0.50",
        "TREND_STATE_PRESTOP_THRESHOLD": "0.50",
        "TREND_STATE_DEBUG": "1",
        "ACTION_MODE": "openfly",

        # Waypoint is only used to describe auxiliary trend state.
        "WAYPOINT_D_SCALE": "12.0",
        "WAYPOINT_Z_SCALE": "5.0",
        "WAYPOINT_USE_Z_DECODE": "1",
        "WAYPOINT_YAW_TURN_THRESHOLD": "0.35",
        "WAYPOINT_Z_THRESHOLD": "1.0",
        "WAYPOINT_FORWARD_POLICY": "distance_bins",

        "EVAL_CONFIG": env.get("EVAL_CONFIG", "configs/eval_test.json"),
    })

    env.pop("PYTHONPATH", None)

    cmd = [sys.executable, "STEER-VLN/eval_hd_lora.py"]

    print("=" * 100)
    print("[STEER-VLN FINAL E3 EVAL CMD]", " ".join(cmd))
    print("[FINAL_MODEL_DIR]", final_dir)
    print("[LOG]", log_path)
    print("=" * 100)

    with open(log_path, "w", encoding="utf-8") as f:
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            env=env,
            cwd=str(ROOT),
            bufsize=1,
        )

        assert proc.stdout is not None

        for line in proc.stdout:
            print(line, end="")
            f.write(line)
            f.flush()

        ret = proc.wait()

    if ret != 0:
        raise RuntimeError(f"STEER-VLN final E3 eval failed with returncode={ret}, log={log_path}")

    print("\\n" + "=" * 100)
    print("[SUMMARY]")
    print("=" * 100)

    summary_keys = [
        "Evaluation complete",
        "Total samples",
        "Valid samples for stop metrics",
        "Image error count",
        "Image error rate",
        "Final accuracy",
        "Pred stop count",
        "Pred stop rate",
        "Successful stop count",
        "Successful stop rate",
        "Forced end count",
        "Forced end rate",
    ]

    text = log_path.read_text(encoding="utf-8", errors="ignore")
    for line in text.splitlines():
        if any(k in line for k in summary_keys):
            print(line)


if __name__ == "__main__":
    main()
